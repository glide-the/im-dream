    expect((await editResponsePromise).status()).toBe(200);
    await expect(editDialog).toBeHidden();
    await expect(taskCard).toContainText('每隔 10 分钟');

    await taskCard.getByRole('button', { name: `更多操作：${taskTitle}` }).click();
