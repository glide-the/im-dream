function diagnosticsFor(page: Page): string[] {
  const diagnostics: string[] = [];
  page.on('pageerror', (error) => diagnostics.push(`pageerror: ${error.message}`));
  page.on('console', (message) => {
    const text = message.text();
    if (message.type() === 'error' && !/(?:react-grab\.com|react-grab\.js|fonts\.googleapis\.com|fonts\.gstatic\.com)/.test(text)) {
      diagnostics.push(`console: ${text}`);
    }
  });
  page.on('requestfailed', (request) => {
    const url = request.url();
    if (request.failure()?.errorText !== 'net::ERR_ABORTED'
      && !/(?:react-grab\.com|react-grab\.js|fonts\.googleapis\.com|fonts\.gstatic\.com)/.test(url)) {
      diagnostics.push(`requestfailed: ${request.failure()?.errorText ?? 'failed'} ${new URL(url).pathname}`);
    }
  });
  page.on('response', (response) => {
    if (response.status() >= 400 && response.url().includes('/api/')) {
      diagnostics.push(`http ${response.status()}: ${new URL(response.url()).pathname}`);
    }
  });
  return diagnostics;
}

async function getJson<T>(request: APIRequestContext, path: string, csrfToken: string): Promise<T> {
  const response = await request.get(`${WEB_BASE}${path}`, { headers: { 'x-ink-csrf': csrfToken } });
  expect(response.status(), await response.text()).toBe(200);
  return response.json() as Promise<T>;
}

async function postJson<T>(request: APIRequestContext, path: string, csrfToken: string, data: unknown): Promise<T> {
  const response = await request.post(`${WEB_BASE}${path}`, {
    headers: {
      'x-ink-csrf': csrfToken,
      origin: WEB_BASE,
      referer: `${WEB_BASE}/`,
    },
    data,
  });
  expect(response.status(), await response.text()).toBe(200);
  return response.json() as Promise<T>;
}

function dateKeyInShanghai(): string {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Shanghai', year: 'numeric', month: '2-digit', day: '2-digit',
  }).formatToParts(new Date());
  const value = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${value.year}-${value.month}-${value.day}`;
}

