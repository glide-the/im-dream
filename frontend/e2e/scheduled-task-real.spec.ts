    let settled: ScheduledTrigger | undefined;
    await expect.poll(async () => {
      expect(await page.locator('[role="alertdialog"]:visible').count(), 'Scheduled execution must not request browser confirmation.').toBe(0);
      const history = await getJson<{ triggers: ScheduledTrigger[] }>(
        page.request, `/api/claude-agent/scheduled-tasks/${encodeURIComponent(taskId)}/history?limit=20`, csrfToken,
      );
      settled = history.triggers.find((trigger) => ['succeeded', 'failed', 'state_unknown'].includes(trigger.status));
      return Boolean(settled);
    }, { timeout: 210_000, intervals: [2_000, 3_000, 5_000] }).toBe(true);
    expect(settled?.status, `Scheduled execution ended with ${settled?.error_code ?? 'no error code'}`).toBe('succeeded');
    expect(settled?.error_code).toBeNull();
    expect(settled?.target_thread_id).toBeTruthy();
    expect(settled?.final_message_id).toBeTruthy();

    const note = await getJson<SessionPayload>(page.request, `/api/sessions/${encodeURIComponent(editorSessionId)}`, csrfToken);
    expect(JSON.stringify(note.editor_state)).toContain(appendedMarker);
    const runHistory = await getJson<ThreadMessages>(
      page.request, `/api/claude-agent/threads/${encodeURIComponent(settled!.target_thread_id!)}/messages`, csrfToken,
    );
    const editorWriteParts = runHistory.messages.flatMap((message) => message.parts)
      .filter((part) => part.toolName === 'mcp__editor__write_segment');
    expect(editorWriteParts.length).toBeGreaterThan(0);
    expect(editorWriteParts.some((part) => part.state === 'output-available' || part.output !== undefined)).toBe(true);

    await detail.getByRole('button', { name: '关闭定时任务详情' }).click();
    await marker.click();
    await expect(detail.getByRole('button', { name: /任务运行会话/ })).toBeVisible();
    const targetMessagesPromise = page.waitForResponse((response) => (
      response.request().method() === 'GET'
      && new URL(response.url()).pathname === `/api/claude-agent/threads/${settled!.target_thread_id}/messages`
    ));
    await detail.getByRole('button', { name: /任务运行会话/ }).click();
    expect((await targetMessagesPromise).status()).toBe(200);
    await expect(page.locator(
      `[data-chat-message-id="${settled!.final_message_id}"]`,
    )).toContainText(appendedMarker, { timeout: 30_000 });

    const workspaceNavigation = page.getByRole('navigation', { name: 'Story Workspace 导航' });
    const moreNavigation = workspaceNavigation.getByRole('button', { name: '更多', exact: true });
    if (await moreNavigation.getAttribute('aria-expanded') !== 'true') await moreNavigation.click();
    await workspaceNavigation.getByRole('button', { name: '写作', exact: true }).click();
    await page.waitForURL(/\/story-workspace\/writing/);
    await expect(page.getByPlaceholder('Start writing...')).toHaveValue(new RegExp(appendedMarker));
    await page.getByRole('button', { name: 'Calendar' }).click();
    const taskCard = page.locator('.calendar-popup__task').filter({ hasText: taskTitle });
    await expect(taskCard).toBeVisible({ timeout: 30_000 });
    await taskCard.getByRole('button', { name: `编辑：${taskTitle}` }).click();
    const editDialog = page.getByRole('dialog', { name: `编辑“${taskTitle}”` });
    await expect(editDialog).toBeVisible();
    await editDialog.getByRole('button', { name: /高级日程/ }).click();
