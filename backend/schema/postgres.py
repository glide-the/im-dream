"""Render the checked-in legacy catalog as ordinary PostgreSQL DDL.

The renderer is intentionally offline and deterministic.  It does not connect
to a database and never adds ``IF NOT EXISTS``: collisions outside the three
explicit baseline-adopt tables must abort the migration transaction.
"""

