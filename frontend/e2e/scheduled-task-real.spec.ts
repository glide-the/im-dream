  await page.getByTitle('New Session').click();
  // New Session first persists the previous note, then replaces the Editor
  // state.  Filling before that asynchronous reset races with the blank load.
  await expect(editor).toHaveValue('', { timeout: 30_000 });
  await editor.fill(noteSeed);
  await expect(editor).toHaveValue(noteSeed);
  const saveResponsePromise = page.waitForResponse((response) => (
    response.request().method() === 'POST'
    && new URL(response.url()).pathname === '/api/sessions'
  ));
  await page.getByRole('button', { name: 'Save today' }).click();
  const saveResponse = await saveResponsePromise;
  expect(saveResponse.status()).toBe(200);
  const savedNote = saveResponse.request().postDataJSON() as {
    session_id?: string; editor_state?: unknown;
  };
  expect(JSON.stringify(savedNote.editor_state)).toContain(taskTitle);
  editorSessionId = String(savedNote.session_id ?? '');
  expect(editorSessionId).not.toBe('');
  await expect(page.getByText('Saved', { exact: true })).toBeVisible();

  await page.getByRole('button', { name: '对话', exact: true }).click();
  await page.waitForURL(/\/story-workspace\/chat/);
  const newChat = page.getByTitle(/^(New chat|新建对话)$/);
  if (await newChat.isVisible().catch(() => false)) await newChat.click();
  const input = page.getByRole('textbox', { name: /^(Chat input|聊天输入)$/ });
  await expect(input).toBeVisible({ timeout: 30_000 });
  const prompt = `请创建一个定时任务：标题为 ${taskTitle}，每隔 1 分钟执行一次，时区 Asia/Shanghai。每次执行时，只使用当前笔记工具在当前笔记末尾追加一行「${appendedMarker}」，不要删除或修改已有内容。创建完成后只回复任务已创建。`;
  await input.fill(prompt);
  const threadResponsePromise = page.waitForResponse((response) => (
    response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/claude-agent/threads'
  ));
  const agentResponsePromise = page.waitForResponse((response) => (
    response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/claude-agent'
  ));
  await page.getByRole('button', { name: /^(Send message|发送消息)$/ }).click();
  const threadResponse = await threadResponsePromise;
  expect(threadResponse.status()).toBe(200);
  const sourceThreadId = (await threadResponse.json() as { thread_id: string }).thread_id;
  const agentResponse = await agentResponsePromise;
  expect(agentResponse.status()).toBe(200);

  const marker = page.locator('.scheduled-task-marker').filter({ hasText: taskTitle });
  await expect(marker).toBeVisible({ timeout: 240_000 });
  await expect(marker).toContainText('每隔 1 分钟');
  await expect(page.getByRole('region', { name: '此对话创建的任务' })).toHaveCount(0);
  await marker.click();
  const detail = page.locator('.scheduled-task-detail');
  await expect(detail).toBeVisible();
  await expect(detail.locator('h3')).toHaveText(['任务信息', '会话', '任务周期']);
  await expect(detail).toContainText('创建任务的会话');
  await page.screenshot({ path: resolve(ARTIFACT_DIR, `${taskTitle}-chat-sidebar.png`), fullPage: true });

  const day = await getJson<{ tasks: ScheduledTask[]; triggers: ScheduledTrigger[] }>(
    page.request,
    `/api/claude-agent/scheduled-tasks/day?local_date=${dateKeyInShanghai()}&display_time_zone=Asia%2FShanghai`,
    csrfToken,
  );
  const created = day.tasks.find((task) => task.title === taskTitle);
  expect(created, `Scheduled task ${taskTitle} was not returned by the production day read.`).toBeDefined();
  expect(created).toMatchObject({ source_thread_id: sourceThreadId, status: 'active', revision: 1,
    rule: { kind: 'interval', interval_minutes: 1, time_zone: 'Asia/Shanghai' } });
  const taskId = created!.id;

