type ScheduledRule =
  | { kind: 'once'; local_date: string; local_time: string; time_zone: string; selected_offset_minutes: number | null }
  | { kind: 'daily'; local_time: string; time_zone: string }
  | { kind: 'interval'; interval_minutes: number; time_zone: string };
type ScheduledTask = {
  id: string; source_thread_id: string; title: string; prompt: string; rule: ScheduledRule;
  next_run_at: string | null; status: 'active' | 'paused' | 'exhausted' | 'deleted'; revision: number;
};
type ScheduledTrigger = {
  id: string; status: 'claimed' | 'queued' | 'running' | 'succeeded' | 'failed' | 'state_unknown' | 'skipped';
  target_thread_id: string | null; final_message_id: string | null; error_code: string | null; created_at: string;
};
type ThreadMessages = {
  thread: { id: string; title?: string | null };
  messages: Array<{ id: string; role: string; parts: Array<{ type?: string; toolName?: string; state?: string; output?: unknown; text?: string }> }>;
};
type SessionPayload = { id: string; name?: string | null; editor_state: unknown };

